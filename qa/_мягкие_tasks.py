def apply_global(path, allow_multi=True):
    s = open(path, encoding='utf8').read()
    miss = []
    for old, new in ЗАМЕНЫ:
        n = s.count(old)
        if n == 0: miss.append(old); continue
        s = s.replace(old, new)
    open(path, 'w', encoding='utf8').write(s)
    return miss

def apply_flow_segments(path):
    s = open(path, encoding='utf8').read()
    seg = []
    for t in ФЛОУ:
        i = s.find("type:'dialog', variant:'flow', title:'%s'" % t)
        if i < 0:
            i = s.find("variant:'flow', title:'%s'" % t)
        assert i > 0, 'нет flow «' + t + '»'
        b = s.find("\n      { type:", i)
        assert b > 0
        seg.append((i, b))
    # заменяем снизу вверх, чтобы индексы сегментов не съезжали
    miss = []
    for (a, b) in sorted(seg, key=lambda x: -x[0]):
        part = s[a:b]
        for old, new in ЗАМЕНЫ:
            if old in part:
                part = part.replace(old, new)
                if old not in [m[0] for m in miss]:
                    miss.append((old, 'найден'))
        s = s[:a] + part + s[b:]
    missed = [o for o, _ in ЗАМЕНЫ if o not in [m[0] for m in miss]]
    open(path, 'w', encoding='utf8').write(s)
    return missed

